export type Lang = 'vi' | 'en';
let currentLang: Lang = (localStorage.getItem('fb_lang') as Lang) || 'vi';

export function getLanguage(): Lang {
  return currentLang;
}

export function setLanguage(lang: Lang): void {
  currentLang = lang;
  try { localStorage.setItem('fb_lang', lang); } catch (_) {}
  applyTexts();
}

export function toggleLanguage(): Lang {
  const next = currentLang === 'vi' ? 'en' : 'vi';
  setLanguage(next);
  return next;
}

export type TextKey = keyof typeof vi;

export function t(key: TextKey | string, vars: Record<string, string | number> = {}): string {
  const dict = currentLang === 'en' ? en : vi;
  const s = (dict as Record<string, string>)[key] ?? (vi as Record<string, string>)[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

/** fill every [data-i18n] element */
export function applyTexts(root: ParentNode = document): void {
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  }
}
